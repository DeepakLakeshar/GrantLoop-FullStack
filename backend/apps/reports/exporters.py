def get_exporter(
    format_name: str,
    data_iterable: Any,
    headers: List[str],
    metadata: Dict[str, Any],
    title: str = "GrantLoop Report",
) -> BaseReportExporter:
    """
    Factory function instantiating the appropriate OOP exporter class based on format string.
    """
    fmt_clean = format_name.lower().strip()
    if fmt_clean not in EXPORTER_REGISTRY:
        raise ValueError(f"Unsupported export format '{format_name}'. Must be one of: {', '.join(EXPORTER_REGISTRY.keys())}")

    class_name = EXPORTER_REGISTRY[fmt_clean]
    exporters_map = {
        "CSVExporter": CSVExporter,
        "ExcelExporter": ExcelExporter,
        "PDFExporter": PDFExporter,
        "ZIPExporter": ZIPExporter,
    }
    target_cls = exporters_map.get(class_name)
    if not target_cls:
        raise ValueError(f"Exporter class {class_name} not found in registry map.")

    return target_cls(data_iterable=data_iterable, headers=headers, metadata=metadata, title=title)
